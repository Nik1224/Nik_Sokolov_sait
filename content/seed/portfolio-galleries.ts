/**
 * Портфолио: кадры с реальных съёмок, разложенные по категориям.
 *
 * Файлы лежат в public/media/portfolio/<категория> в трёх размерах: 600 для
 * сетки на телефоне, 1200 для сетки на компьютере, 1800 для полного экрана.
 * EXIF снят при пережатии — модель камеры и софт в вебе не нужны.
 *
 * Список собран из имён файлов, поэтому добавление кадра сводится к пережатию
 * и одной строке здесь. После подключения CMS галереи переедут в неё целиком.
 */

import type { MediaAsset } from '@/content/types';

const WIDTHS = [600, 1200, 1800] as const;

/**
 * Описания у кадров порядковые: придумывать за фотографа, что происходит на
 * чужой съёмке, нельзя. Настоящие подписи заводятся в CMS по кадру.
 */
function frame(
  folder: string,
  id: string,
  width: number,
  height: number,
  index: number,
  ru: string,
  en: string,
): MediaAsset {
  const base = `/media/portfolio/${folder}`;
  return {
    _key: `${folder}-${id}`,
    type: 'image',
    rights: 'owned',
    alt: { ru: `${ru}, кадр ${index}`, en: `${en}, frame ${index}` },
    image: {
      src: `${base}/${id}-1800.jpg`,
      width,
      height,
      sources: WIDTHS.map((size) => ({ width: size, src: `${base}/${id}-${size}.jpg` })),
    },
  };
}

